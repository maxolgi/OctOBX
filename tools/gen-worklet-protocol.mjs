#!/usr/bin/env node
// ===========================================================================
// gen-worklet-protocol.mjs — generates every consumable artifact of the
// worklet message-protocol spec.
//
// SOURCE OF TRUTH: tools/worklet-protocol.mjs. This generator consumes
// exactly that spec and emits two committed outputs:
//
//   1. src/generated/worklet-protocol.ts         TypeScript discriminated
//                                               unions (MainToWorkletMsg /
//                                               WorkletToMainMsg) for the
//                                               main thread
//   2. src/generated/worklet-protocol-checks.js  classic-script shape
//                                               validator for MAIN→WORKLET
//                                               messages (the direction the
//                                               worklet receives); build.sh
//                                               concatenates it into the
//                                               combined worklet when the
//                                               dev checks flag is on
//                                               (`combine_worklet 1`)
//
// Usage:
//   node tools/gen-worklet-protocol.mjs           # write both outputs
//   node tools/gen-worklet-protocol.mjs --check   # byte-compare against the
//                                                # committed files; exit 0
//                                                # fresh, exit 1 listing
//                                                # stale paths
//
// Deterministic by construction: stable ordering, no timestamps — --check is
// byte-stable across runs on the same spec. Node >= 20, no dependencies.
// ===========================================================================

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PROTOCOL, parseFieldDsl, validateProtocol } from './worklet-protocol.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

const OUT_TS = 'src/generated/worklet-protocol.ts';
const OUT_CHECKS = 'src/generated/worklet-protocol-checks.js';

// ---------------------------------------------------------------------------
// Field DSL views (parseFieldDsl throws on anything outside the vocabulary —
// the generator itself is the closed-set enforcer).
// ---------------------------------------------------------------------------

// TS type for one field's DSL.
function tsType(parsed) {
    let t;
    switch (parsed.base) {
        case 'int':
        case 'number':
        case 'flag':
            t = 'number';
            break;
        case 'bool':
            t = 'boolean';
            break;
        case 'bytes':
            t = 'Uint8Array';
            break;
        case 'f32':
            t = 'Float32Array';
            break;
        case 'string':
            t = 'string';
            break;
        case 'number[]':
            t = 'number[]';
            break;
        default:
            throw new Error(`unreachable base ${parsed.base}`);
    }
    if (parsed.nullable) t += ' | null';
    return t;
}

// Compact check-code for one field's DSL: single-char kind + fixed length
// (informational) + '?'/'|null' suffixes. See the checks-file header.
function checkCode(parsed) {
    let c;
    switch (parsed.base) {
        case 'int':
        case 'number':
        case 'flag':
            c = 'n';
            break;
        case 'bool':
            c = 'b';
            break;
        case 'string':
            c = 's';
            break;
        case 'bytes':
            c = 'u8';
            break;
        case 'f32':
            c = 'f32';
            break;
        case 'number[]':
            c = 'a' + (parsed.fixedLen ?? '');
            break;
        default:
            throw new Error(`unreachable base ${parsed.base}`);
    }
    if (parsed.nullable) c += '|null';
    if (parsed.optional) c += '?';
    return c;
}

// ---------------------------------------------------------------------------
// Output 1: src/generated/worklet-protocol.ts
// ---------------------------------------------------------------------------

function genTs() {
    const L = [];
    const push = (...lines) => L.push(...lines);

    push(
        '/**',
        ' * worklet-protocol.ts — GENERATED worklet message-protocol types: the',
        ' * discriminated unions for the main-thread side of the port protocol.',
        ' *',
        ' * AUTO-GENERATED by tools/gen-worklet-protocol.mjs — DO NOT EDIT THIS FILE BY',
        ' * HAND. Source of truth: tools/worklet-protocol.mjs.',
        ' *',
        ' * Regenerate with:    node tools/gen-worklet-protocol.mjs',
        ' * Freshness check:    node tools/gen-worklet-protocol.mjs --check   (CI gate)',
        ' *',
        ` * ${PROTOCOL.mainToWorklet.length} main→worklet + ${PROTOCOL.workletToMain.length} worklet→main types.`,
        ' *',
        ' * DSL→TS mapping: int/number/flag → number, bool → boolean, bytes →',
        ' * Uint8Array, f32 → Float32Array, string → string, number[] → number[]',
        ' * (fixed lengths collapse to plain number[] with the length noted in a',
        ' * trailing comment). Ranges and fixed lengths are documentation only —',
        " * the worklet-side shape validator (worklet-protocol-checks.js) does NOT",
        ' * enforce them.',
        ' */',
        '',
    );

    const union = (name, doc, entries) => {
        push(`/** ${doc} */`);
        push(`export type ${name} =`);
        for (const e of entries) {
            const fields = Object.entries(e.fields).map(([name2, dsl]) => {
                const p = parseFieldDsl(dsl);
                const opt = p.optional ? '?' : '';
                const len = p.fixedLen !== null ? ` /* ${p.fixedLen} */` : '';
                return `${name2}${opt}: ${tsType(p)}${len}`;
            });
            const body = fields.length > 0 ? ` { type: '${e.type}'; ${fields.join('; ')} }` : ` { type: '${e.type}' }`;
            push(`    |${body} // ${e.notes}`);
        }
        push('');
    };

    union('MainToWorkletMsg', 'Messages the main thread posts to the combined OB-Xf/Octopus AudioWorklet.', PROTOCOL.mainToWorklet);
    union('WorkletToMainMsg', 'Replies and events the worklet posts back to the main thread.', PROTOCOL.workletToMain);

    return L.join('\n');
}

// ---------------------------------------------------------------------------
// Output 2: src/generated/worklet-protocol-checks.js
// ---------------------------------------------------------------------------

function genChecks() {
    const L = [];
    const push = (...lines) => L.push(...lines);

    push(
        '/*',
        ' * worklet-protocol-checks.js — GENERATED shape validator for MAIN→WORKLET',
        ' * messages (the direction the worklet receives).',
        ' *',
        ' * AUTO-GENERATED by tools/gen-worklet-protocol.mjs — DO NOT EDIT THIS FILE BY',
        ' * HAND. Source of truth: tools/worklet-protocol.mjs.',
        ' *',
        ' * Regenerate with:    node tools/gen-worklet-protocol.mjs',
        ' * Freshness check:    node tools/gen-worklet-protocol.mjs --check   (CI gate)',
        ' *',
        ' * Plain classic script (no import/export): build.sh concatenates this file',
        ' * into wasm/build/obxd-processor.js (right after src/generated/restore-',
        ' * layout.js) when the dev checks flag is on — `combine_worklet 1`, used by',
        " * the `synth` case for dev iteration. Production builds (app/desktop/all)",
        ' * omit it.',
        ' *',
        ' * __workletProtocolCheck(msg) returns null when the message is well-shaped',
        " * (or not an object — nothing to check), otherwise a '<type>: ...' error",
        ' * string. NEVER throws. Shape-only by design: NO range checks, NO',
        ' * fixed-length checks — cheap and false-positive-free on the',
        ' * message-handler thread.',
        ' *',
        ' * Field codes: n = number (int/number/flag), b = boolean, s = string,',
        ' * u8 = Uint8Array view, f32 = Float32Array view, aNN = number[] (length',
        " * informational only). Suffixes: '?' = optional, '|null' = nullable.",
        ' */',
        '',
        "const WP_KIND_LABELS = { n: 'number', b: 'boolean', s: 'string', u: 'bytes', f: 'f32', a: 'number[]' };",
        '',
        'const WP_FIELDS = {',
    );
    for (const e of PROTOCOL.mainToWorklet) {
        const parts = Object.entries(e.fields).map(([name, dsl]) => `${name}:${checkCode(parseFieldDsl(dsl))}`);
        push(`    ${e.type}: '${parts.join(',')}',`);
    }
    push(
        '};',
        '',
        '/**',
        ' * Validate one MAIN→WORKLET message. See the file header for the return',
        ' * contract. This is the ONLY function defined here.',
        ' * @param {unknown} msg',
        ' * @returns {string|null}',
        ' */',
        'function __workletProtocolCheck(msg) {',
        '    try {',
        '        if (typeof msg !== \'object\' || msg === null) return null;',
        '        if (!Object.prototype.hasOwnProperty.call(WP_FIELDS, msg.type)) {',
        "            return \"unknown message type '\" + msg.type + \"'\";",
        '        }',
        "        const spec = WP_FIELDS[msg.type];",
        "        if (spec === '') return null;",
        '        const entries = spec.split(\',\');',
        '        for (let i = 0; i < entries.length; i++) {',
        '            const e = entries[i];',
        "            const ci = e.indexOf(':');",
        '            const name = e.slice(0, ci);',
        '            let code = e.slice(ci + 1);',
        "            const optional = code.charCodeAt(code.length - 1) === 63; // '?'",
        '            if (optional) code = code.slice(0, -1);',
        "            const nullable = code.slice(-5) === '|null';",
        '            if (nullable) code = code.slice(0, -5);',
        '            const kind = code.charAt(0);',
        '            const v = msg[name];',
        '            if (v === undefined) {',
        '                if (optional) continue;',
        "                return msg.type + \": missing field '\" + name + \"'\";",
        '            }',
        '            if (v === null && nullable) continue;',
        '            let ok = false;',
        "            if (kind === 'n') ok = typeof v === 'number';",
        "            else if (kind === 'b') ok = typeof v === 'boolean';",
        "            else if (kind === 's') ok = typeof v === 'string';",
        "            else if (kind === 'u') ok = typeof v === 'object' && v !== null && ArrayBuffer.isView(v) && v instanceof Uint8Array;",
        "            else if (kind === 'f') ok = typeof v === 'object' && v !== null && ArrayBuffer.isView(v) && v instanceof Float32Array;",
        "            else if (kind === 'a') ok = Array.isArray(v);",
        '            if (!ok) {',
        '                return msg.type + ": field \'" + name + "\' expected " + WP_KIND_LABELS[kind] +',
        '                    ", got " + (v === null ? \'null\' : typeof v);',
        '            }',
        '        }',
        '        return null;',
        '    } catch (err) {',
        '        return String(err);',
        '    }',
        '}',
        '',
        '// registerProcessor-style scope note (awp-task-queue.js pattern): in the',
        '// concatenated worklet script the consts + function above are directly',
        '// visible to obxd-processor.tail.js (same classic-script top-level scope).',
        '// For the vitest (node ESM) import path — where top-level declarations do',
        '// NOT leak onto the shared global — register on globalThis so tests can',
        '// grab them after the side-effect import:',
        'if (typeof globalThis !== \'undefined\') {',
        '    globalThis.__workletProtocolCheck = __workletProtocolCheck;',
        '    globalThis.WORKLET_PROTOCOL_TYPES = new Set([',
    );
    const sorted = [...PROTOCOL.mainToWorklet.map((e) => `'${e.type}'`)].sort();
    for (let i = 0; i < sorted.length; i += 4) {
        push('        ' + sorted.slice(i, i + 4).join(', ') + ',');
    }
    push(
        '    ]);',
        '}',
        '',
    );

    return L.join('\n');
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

function main() {
    const problems = validateProtocol();
    if (problems.length > 0) {
        console.error('tools/worklet-protocol.mjs failed its self-check — refusing to generate:');
        for (const p of problems) console.error(`  - ${p}`);
        process.exit(2);
    }

    const outputs = [
        { rel: OUT_TS, content: genTs() },
        { rel: OUT_CHECKS, content: genChecks() },
    ];

    if (process.argv.includes('--check')) {
        const stale = [];
        for (const { rel, content } of outputs) {
            let committed = null;
            try {
                committed = readFileSync(join(ROOT, rel), 'utf8');
            } catch {
                stale.push(rel);
                continue;
            }
            if (committed !== content) stale.push(rel);
        }
        if (stale.length > 0) {
            console.error('STALE generated outputs (regenerate with `node tools/gen-worklet-protocol.mjs`):');
            for (const rel of stale) console.error(`  ${rel}`);
            process.exit(1);
        }
        console.log(`OK — all ${outputs.length} generated outputs are fresh`);
        return;
    }

    for (const { rel, content } of outputs) {
        const abs = join(ROOT, rel);
        mkdirSync(dirname(abs), { recursive: true });
        writeFileSync(abs, content);
        console.log(`wrote ${rel}`);
    }
    console.log(
        `worklet protocol: ${PROTOCOL.mainToWorklet.length} main→worklet + ` +
        `${PROTOCOL.workletToMain.length} worklet→main types`,
    );
}

main();
