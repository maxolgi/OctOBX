#!/usr/bin/env node
/*
 * prep-mixer-wasm.mjs — pull the CakeMix mixer engine (Rust `mixer-wasm`,
 * the oximedia-mixer port) into OctOBX as self-contained artifacts.
 *
 * Reads the sibling CakeMix checkout's wasm-bindgen pkg:
 *   ../CakeMix/crates/mixer-wasm/pkg/mixer_wasm.js       (ES-module glue)
 *   ../CakeMix/crates/mixer-wasm/pkg/mixer_wasm_bg.wasm  (engine binary)
 * and writes into this repo (committed so builds don't need CakeMix/cargo):
 *   wasm/mixer/mixer_wasm_glue.js   — glue stripped to a classic script
 *                                     (defines top-level `initSync` +
 *                                     `MixerWasm`, concatenated by build.sh
 *                                     into the combined worklet script)
 *   wasm/mixer/mixer_wasm_bg.wasm   — the engine binary (served at / by
 *                                     vite's publicDir = wasm/build, copied
 *                                     there by build.sh)
 *
 * The ES-module stripping mirrors CakeMix's build/build-worklet.js (same
 * regexes): AudioWorkletGlobalScope forbids importScripts()/dynamic import(),
 * so the only way to ship the glue is inside the same classic script fed to
 * audioWorklet.addModule().
 *
 * Usage:
 *   node tools/prep-mixer-wasm.mjs            # default ../CakeMix lookup
 *   CAKEMIX_DIR=/path node tools/prep-mixer-wasm.mjs
 *
 * Re-run manually whenever the CakeMix mixer engine changes, then rebuild
 * (`./build.sh synth`).
 */

import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const cakeDir = process.env.CAKEMIX_DIR || join(repoRoot, "..", "CakeMix");
const pkgDir = join(cakeDir, "crates", "mixer-wasm", "pkg");
const outDir = join(repoRoot, "wasm", "mixer");

let glue;
try {
    glue = readFileSync(join(pkgDir, "mixer_wasm.js"), "utf-8");
} catch (e) {
    console.error(`ERROR: cannot read ${join(pkgDir, "mixer_wasm.js")} — ` +
        `set CAKEMIX_DIR or initialize the sibling CakeMix checkout.`);
    process.exit(1);
}

// Guard: a node-target pkg (e.g. left behind by `make test-wasm`) inlines
// require('fs') to load the wasm — that throws in AudioWorkletGlobalScope.
// (Same check as CakeMix's build/build-worklet.js.)
if (/require\(/.test(glue)) {
    console.error("ERROR: pkg glue is a node-target build (contains require()).");
    console.error("       Rebuild the web-target pkg in CakeMix (make build-web).");
    process.exit(1);
}

// Strip ES module syntax (classic script for addModule()).
glue = glue.replace(/^export\s+/gm, "");
glue = glue.replace(/^export\s*\{[^}]+\};?\s*$/gm, "");
glue = glue.replace(/^\{\s*initSync[\s\S]*?\};\s*$/gm, "");
glue = glue.replace(/^\{\s*\w+\s+as\s+\w+\s*\};?\s*$/gm, "");
glue = glue.replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, "");
glue = glue.replace(/module_or_path\s*=\s*new URL\([^)]+\);/m,
    "module_or_path = undefined; // stripped for worklet");
glue = glue.replace(/^exports\.\w+\s*=\s*\w+;?\s*$/gm, "");
glue = glue.replace(/^module\.exports\s*=\s*\{[\s\S]*?\};?\s*$/gm, "");
glue = glue.replace(/^const\s+\w+\s*=\s*require\([^)]+\);?\s*$/gm, "");

const header = [
    "// AUTO-GENERATED by tools/prep-mixer-wasm.mjs — do not edit by hand.",
    "// Source: CakeMix crates/mixer-wasm/pkg/mixer_wasm.js (wasm-bindgen,",
    "// web target), stripped to a classic script for AudioWorkletGlobalScope.",
    "//",
    "// The glue body is wrapped in an IIFE: its internal top-level lets",
    "// (`wasmModule`, `wasm`, `cachedTextDecoder`, …) would collide with the",
    "// combined worklet script's own declarations (the processor tail already",
    "// declares `wasmModule`). Only two bridge names escape the IIFE, exposed",
    "// as top-level vars in the script's declarative record (bare-name access",
    "// from the tail — the same mechanism the emcc factory names rely on):",
    "//   __cmxInitSync(module) — initSync({module: new WebAssembly.Module(bytes)})",
    "//   __cmxMixerWasm        — the MixerWasm class (constructor + methods)",
    "",
    "var __cmxInitSync, __cmxMixerWasm;",
    "(function () {",
    "",
].join("\n");

const footer = [
    "",
    "__cmxInitSync = initSync;",
    "__cmxMixerWasm = MixerWasm;",
    "})();",
    "",
].join("\n");

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "mixer_wasm_glue.js"), header + glue + footer);
copyFileSync(join(pkgDir, "mixer_wasm_bg.wasm"), join(outDir, "mixer_wasm_bg.wasm"));
console.log(`Wrote ${join(outDir, "mixer_wasm_glue.js")} (${glue.length} bytes of glue)`);
console.log(`Copied ${join(outDir, "mixer_wasm_bg.wasm")}`);
